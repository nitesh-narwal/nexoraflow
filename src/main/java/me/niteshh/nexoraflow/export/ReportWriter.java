package me.niteshh.nexoraflow.export;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import org.springframework.stereotype.Service;

import me.niteshh.nexoraflow.configuration.JsonSupport;
import me.niteshh.nexoraflow.configuration.NexoraProperties;
import me.niteshh.nexoraflow.evaluation.EvaluationReport;
import me.niteshh.nexoraflow.generator.GeneratorSettings;
import me.niteshh.nexoraflow.reporting.ReportingService;
import me.niteshh.nexoraflow.validation.ValidationReport;

/** Writes the machine-readable reports and their human-readable summaries. */
@Service
public class ReportWriter {

    private final JsonSupport json;
    private final NexoraProperties properties;
    private final ReportingService reporting;

    public ReportWriter(JsonSupport json, NexoraProperties properties, ReportingService reporting) {
        this.json = json;
        this.properties = properties;
        this.reporting = reporting;
    }

    public void writeAll(GeneratorSettings settings, ValidationReport validation, EvaluationReport evaluation) {
        Path base = Path.of(properties.generator().outputDir());
        try {
            Files.createDirectories(base.resolve("reports"));
            Files.createDirectories(base.resolve("manifests"));
            write(base.resolve("manifests/validation_summary.json"), json.toPrettyJson(validation));
            write(base.resolve("reports/validation_report.json"), json.toPrettyJson(validation));
            write(base.resolve("reports/evaluation_report.json"), json.toPrettyJson(evaluation));
            write(base.resolve("reports/evaluation_summary.md"), evaluationMarkdown(settings, evaluation));
            Map<String, Object> metrics = reporting.summary();
            write(base.resolve("reports/operational_metrics.json"), json.toPrettyJson(metrics));
            write(base.resolve("reports/decision_summary.md"), decisionMarkdown(metrics));
            Path docs = Path.of(properties.generator().docsDir());
            if (Files.isDirectory(docs)) {
                write(docs.resolve("validation-report.md"), validationMarkdown(settings, validation, evaluation));
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void write(Path path, String content) throws IOException {
        Files.writeString(path, content.endsWith("\n") ? content : content + "\n", StandardCharsets.UTF_8);
    }

    // ------------------------------------------------------------------ markdown

    public String validationMarkdown(GeneratorSettings s, ValidationReport v, EvaluationReport e) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Validation report\n\n");
        sb.append("> Generated by `NexoraFlow` for seed `").append(s.seed()).append("`, profile `").append(s.profile())
                .append("`, reference date `").append(s.referenceDate()).append("`, business rules `").append(properties.businessRulesVersion())
                .append("`. This file is produced by the validation module, not written by hand; re-generate it with `scripts/full-pipeline.sh`.\n\n");
        sb.append("## Result\n\n");
        sb.append("| Checks | Passed | Failed | Informational | Findings (errors) |\n|---:|---:|---:|---:|---:|\n");
        var sum = v.summary();
        sb.append("| ").append(sum.checks()).append(" | ").append(sum.passed()).append(" | ").append(sum.failed()).append(" | ")
                .append(sum.informational()).append(" | ").append(sum.totalFindings()).append(" |\n\n");
        sb.append("**Overall: ").append(sum.allPassed() ? "PASS" : "FAIL").append("**\n\n");
        sb.append("## Checks\n\n| ID | Category | Check | Status | Findings |\n|---|---|---|---|---:|\n");
        for (ValidationReport.CheckResult c : v.checks()) {
            sb.append("| ").append(c.id()).append(" | ").append(c.category()).append(" | ").append(c.name()).append(" | ")
                    .append(c.status()).append(" | ").append(c.findingCount()).append(" |\n");
        }
        sb.append("\nPASS = no violating record. INFO = an expected, explained condition (deliberately invalid submissions that were preserved "
                + "instead of being discarded or corrupting canonical tables).\n\n");
        for (ValidationReport.CheckResult c : v.checks()) {
            if (c.findingCount() > 0) {
                sb.append("### ").append(c.id()).append(" - ").append(c.name()).append(" (").append(c.status()).append(")\n\n")
                        .append(c.description()).append("\n\n");
                for (ValidationReport.Finding f : c.findings().subList(0, Math.min(10, c.findings().size()))) {
                    sb.append("- `").append(f.entityId()).append("` ").append(f.message()).append("\n");
                }
                sb.append("\n");
            }
        }
        sb.append("## Evaluation against ground truth\n\n").append(evaluationSection(e));
        return sb.toString();
    }

    public String evaluationMarkdown(GeneratorSettings s, EvaluationReport e) {
        return "# Evaluation summary\n\n> Seed `" + s.seed() + "`, profile `" + s.profile() + "`. " + e.meta().note() + "\n\n" + evaluationSection(e);
    }

    private String evaluationSection(EvaluationReport e) {
        StringBuilder sb = new StringBuilder();
        var a = e.anomalyDetection();
        var w = e.workflowDecisions();
        var r = e.reimbursementDecisions();
        sb.append("### Anomaly detection (anomaly-labelled entities vs. valid entities)\n\n");
        sb.append("| Anomalies labelled | Detected | Undetected (FN) | False positives | Precision | Recall | F1 |\n|---:|---:|---:|---:|---:|---:|---:|\n");
        sb.append("| ").append(a.anomaliesLabelled()).append(" | ").append(a.detected()).append(" | ").append(a.undetected()).append(" | ")
                .append(a.falsePositives()).append(" | ").append(a.precision()).append(" | ").append(a.recall()).append(" | ").append(a.f1()).append(" |\n\n");
        sb.append("### Ordinary workflow decisions\n\n");
        sb.append("| Evaluated | Correct outcome | Incorrect | Outcome accuracy | Paths evaluated | Correct paths | Path accuracy | Decision accuracy |\n|---:|---:|---:|---:|---:|---:|---:|---:|\n");
        sb.append("| ").append(w.evaluated()).append(" | ").append(w.correctOutcome()).append(" | ").append(w.incorrectOutcome()).append(" | ")
                .append(w.outcomeAccuracy()).append(" | ").append(w.pathEvaluated()).append(" | ").append(w.correctPath()).append(" | ")
                .append(w.pathAccuracy()).append(" | ").append(w.decisionAccuracy()).append(" |\n\n");
        sb.append("### Reimbursement decisions\n\n| Claims evaluated | Correct | Incorrect | Accuracy | Claims with >1 reimbursement |\n|---:|---:|---:|---:|---:|\n");
        sb.append("| ").append(r.evaluated()).append(" | ").append(r.correct()).append(" | ").append(r.incorrect()).append(" | ")
                .append(r.accuracy()).append(" | ").append(r.claimsWithMoreThanOneReimbursement()).append(" |\n\n");
        var c = e.controls();
        sb.append("### Safeguards that fired (from the audit trail)\n\n");
        sb.append("- Invalid reimbursement requests prevented (duplicate or not eligible): **").append(c.invalidReimbursementsPrevented()).append("** (duplicates: ")
                .append(c.duplicateReimbursementAttempts()).append(")\n");
        sb.append("- Unauthorized / self-approval attempts prevented: **").append(c.unauthorizedApprovalAttemptsPrevented()).append("**\n");
        sb.append("- Failed lifecycle transitions rejected and recorded: **").append(c.failedLifecycleTransitions()).append("**\n");
        sb.append("- Submissions preserved with invalid references: **").append(c.invalidReferencesPreserved()).append("** (rejected at intake: ")
                .append(c.submissionsRejectedAtIntake()).append(")\n");
        sb.append("- Foreign-key validation failures (check DI-02): **").append(c.foreignKeyValidationFailures()).append("**\n");
        sb.append("- Duplicate business identifiers (check DI-01): **").append(c.duplicateBusinessIdentifiers()).append("**\n\n");
        var t = e.totals();
        sb.append("### Record volumes\n\nTotal canonical records: **").append(t.totalRecords()).append("**; valid labelled entities: ").append(t.validRecords())
                .append("; entities of designed anomaly scenarios: ").append(t.invalidRecords()).append("; unlabelled requests: ").append(t.unlabelledRequests()).append("\n\n");
        sb.append("| Table | Rows |\n|---|---:|\n");
        t.recordsGenerated().forEach((k, v) -> sb.append("| ").append(k).append(" | ").append(v).append(" |\n"));
        sb.append("\n### Per scenario\n\n| Issue type | Anomaly | Entities | Outcome correct | Evidence found |\n|---|---|---:|---:|---:|\n");
        for (EvaluationReport.ScenarioBreakdown sc : e.scenarios()) {
            sb.append("| ").append(sc.issueType()).append(" | ").append(sc.anomaly() ? "yes" : "no").append(" | ").append(sc.total()).append(" | ")
                    .append(sc.outcomeCorrect()).append(" | ").append(sc.reasonOrEvidenceCorrect()).append(" |\n");
        }
        if (!e.mismatches().isEmpty()) {
            sb.append("\n### Mismatches (first ").append(Math.min(25, e.mismatches().size())).append(")\n\n");
            e.mismatches().subList(0, Math.min(25, e.mismatches().size())).forEach(m -> sb.append("- `").append(m.entityId()).append("` ")
                    .append(m.problem()).append(": expected ").append(m.expectedOutcome()).append(" / actual ").append(m.actualOutcome()).append("\n"));
        } else {
            sb.append("\nNo mismatches between engine results and ground truth.\n");
        }
        return sb.toString();
    }

    @SuppressWarnings("unchecked")
    private String decisionMarkdown(Map<String, Object> metrics) {
        StringBuilder sb = new StringBuilder("# Decision summary\n\nEvery figure below is calculated from the source records.\n\n");
        Map<String, Object> exceptions = (Map<String, Object>) metrics.get("exceptions");
        sb.append("## Decisions by reason code\n\n| Reason code | Entity type | Count |\n|---|---|---:|\n");
        for (Map<String, Object> row : (List<Map<String, Object>>) exceptions.get("decisionsByReasonCode")) {
            sb.append("| ").append(row.get("code")).append(" | ").append(row.get("entity_type")).append(" | ").append(row.get("count")).append(" |\n");
        }
        sb.append("\n## Open exceptions\n\n| Entity | Status | Count |\n|---|---|---:|\n");
        for (Map<String, Object> row : (List<Map<String, Object>>) exceptions.get("openExceptions")) {
            sb.append("| ").append(row.get("entity_type")).append(" | ").append(row.get("status")).append(" | ").append(row.get("count")).append(" |\n");
        }
        sb.append("\n## Detected anomalies\n\n| Anomaly type | Severity | Count |\n|---|---|---:|\n");
        for (Map<String, Object> row : (List<Map<String, Object>>) exceptions.get("detectedAnomaliesByType")) {
            sb.append("| ").append(row.get("anomaly_type")).append(" | ").append(row.get("severity")).append(" | ").append(row.get("count")).append(" |\n");
        }
        return sb.toString();
    }
}
